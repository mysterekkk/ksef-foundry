<?php
declare(strict_types=1);

/*
 * NOTICE (KSeF Foundry, MIT, author LuroWeb)
 *
 * Creates LOCAL, offline-usable derived copies of the official FA(3) XSD bundle.
 *
 * Source (official, Ministry of Finance, unchanged copies kept in schemas/xsd/FA/):
 *   schemat_FA3_v1-0E.xsd           (targetNamespace http://crd.gov.pl/wzor/2025/06/25/13775/)
 *   bazowe/StrukturyDanych_v10-0E.xsd
 *   bazowe/ElementarneTypyDanych_v10-0E.xsd
 *   bazowe/KodyKrajow_v10-0E.xsd
 *
 * The ONLY transformation: the value of `schemaLocation="..."` attributes that point to
 * http(s)://crd.gov.pl/... is replaced by a relative local path (the remote URL's file name
 * is looked up in the bundle). Every other byte (copyright header, annotations, line endings,
 * whitespace) is preserved. Files without a remote schemaLocation are copied byte-for-byte.
 *
 * Outputs (byte-identical):
 *   schemas/xsd/FA/resolved/                (committed, derived)
 *   packages/php/resources/xsd/FA3/         (shipped inside the Composer package)
 * Each also receives NOTICE.txt and SHA256SUMS.txt (source + resolved hashes).
 *
 * Usage: php scripts/resolve-xsd.php
 */

$root = dirname(__DIR__);
$srcDir = $root . '/schemas/xsd/FA';
$files = [
    'schemat_FA3_v1-0E.xsd',
    'bazowe/StrukturyDanych_v10-0E.xsd',
    'bazowe/ElementarneTypyDanych_v10-0E.xsd',
    'bazowe/KodyKrajow_v10-0E.xsd',
];
$targets = [$srcDir . '/resolved', $root . '/packages/php/resources/xsd/FA3'];

$byBase = [];
foreach ($files as $f) {
    $byBase[basename($f)] = $f;
}

$sums = [];
$out = [];
foreach ($files as $f) {
    $raw = file_get_contents($srcDir . '/' . $f);
    if ($raw === false) {
        fwrite(STDERR, "cannot read $f\n");
        exit(1);
    }
    $dir = dirname($f) === '.' ? '' : dirname($f) . '/';
    $new = preg_replace_callback(
        '/schemaLocation="([^"]*)"/',
        static function (array $m) use ($byBase, $dir, $f): string {
            $loc = $m[1];
            $base = basename(parse_url($loc, PHP_URL_PATH) ?: $loc);
            if (!isset($byBase[$base])) {
                fwrite(STDERR, "unresolvable schemaLocation $loc in $f\n");
                exit(1);
            }
            $target = $byBase[$base];
            // relative path from the directory of $f to $target
            $from = $dir === '' ? [] : explode('/', rtrim($dir, '/'));
            $to = explode('/', $target);
            while ($from !== [] && $to !== [] && count($to) > 1 && $from[0] === $to[0]) {
                array_shift($from);
                array_shift($to);
            }
            $rel = str_repeat('../', count($from)) . implode('/', $to);
            return 'schemaLocation="' . $rel . '"';
        },
        $raw,
    );
    if ($new === null) {
        exit(1);
    }
    if (preg_match('#schemaLocation="https?://#', $new)) {
        fwrite(STDERR, "remote schemaLocation left in $f\n");
        exit(1);
    }
    $out[$f] = $new;
    $sums[] = sprintf("source   %s  %s", hash('sha256', $raw), $f);
}
foreach ($out as $f => $c) {
    $sums[] = sprintf("resolved %s  %s", hash('sha256', $c), $f);
}

$notice = "Derived copies of the official FA(3) XSD (Ministry of Finance).\n"
    . "Only schemaLocation attributes were rewritten from remote crd.gov.pl URLs to local relative paths.\n"
    . "Generated by scripts/resolve-xsd.php (KSeF Foundry, MIT, LuroWeb). Do not edit by hand.\n"
    . "Original copyright headers inside the XSD files are untouched.\n";

foreach ($targets as $t) {
    foreach ($out as $f => $c) {
        $p = $t . '/' . $f;
        if (!is_dir(dirname($p))) {
            mkdir(dirname($p), 0777, true);
        }
        file_put_contents($p, $c);
    }
    file_put_contents($t . '/NOTICE.txt', $notice);
    file_put_contents($t . '/SHA256SUMS.txt', implode("\n", $sums) . "\n");
}
echo implode("\n", $sums), "\n";
